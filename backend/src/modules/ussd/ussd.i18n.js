export const t = (lang, key, vars = {}) => {
  const table = STRINGS[lang] || STRINGS[DEFAULT_LANGUAGE];
  const template = table[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? '' : String(vars[k])));
};

export default { t, SUPPORTED_LANGUAGES, DEFAULT_LANGUAGE };
